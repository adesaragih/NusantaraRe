-- Jalur mundur 025: buang kolom IDPEGA peserta klaim (berpelindung, aman diulang).

DECLARE
  n NUMBER;
BEGIN
  SELECT COUNT(*) INTO n FROM SYS.ALL_TAB_COLUMNS
   WHERE OWNER = UPPER('{skema}') AND TABLE_NAME = 'T_CLAIMLF_PREMIUMLIST_DETAIL' AND COLUMN_NAME = 'IDPEGA';
  IF n > 0 THEN
    EXECUTE IMMEDIATE 'ALTER TABLE {skema}.T_CLAIMLF_PREMIUMLIST_DETAIL DROP COLUMN IDPEGA';
  END IF;
END;
/
