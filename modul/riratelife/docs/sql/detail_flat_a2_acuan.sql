PROMPT 2. Sidik isi per kolom (cacah tidak-NULL + jumlah ORA_HASH) dan per baris
SELECT COUNT(IDUSEDBY) N_IDUSEDBY, COUNT(USEDBY) N_USEDBY, COUNT(TYPE) N_TYPE, COUNT(GENDER) N_GENDER,
       COUNT(CONTRACT) N_CONTRACT, COUNT(AGE) N_AGE, COUNT(RATE) N_RATE FROM POOLDATA.RATE_LIFE;
SELECT SUM(ORA_HASH(IDUSEDBY)) H_IDUSEDBY, SUM(ORA_HASH(USEDBY)) H_USEDBY, SUM(ORA_HASH(TYPE)) H_TYPE,
       SUM(ORA_HASH(GENDER)) H_GENDER FROM POOLDATA.RATE_LIFE;
SELECT SUM(ORA_HASH(CONTRACT)) H_CONTRACT, SUM(ORA_HASH(AGE)) H_AGE, SUM(ORA_HASH(RATE)) H_RATE,
       SUM(ORA_HASH(ID || '|' || IDUSEDBY || '|' || USEDBY || '|' || TYPE || '|' || GENDER || '|' || CONTRACT
                   || '|' || AGE || '|' || RATE)) H_BARIS
  FROM POOLDATA.RATE_LIFE;
PROMPT 3. Yatim (IDUSEDBY tanpa ringkasan) dan status prosedur Pega
