 WHERE NOT EXISTS (SELECT 1 FROM POOLDATA.M_RATE_LIFE_SUMMARY s WHERE s.ID = r.IDUSEDBY);
SELECT OBJECT_NAME, OBJECT_TYPE, STATUS FROM SYS.ALL_OBJECTS WHERE OWNER = 'POOLDATA' AND OBJECT_NAME = 'PEGA_M_RATE_LIFE';
