-- 205 - tab Scoring Risk kasus FIRE (tiket 54): halaman `.OfferFacIn.ScoringRisk` ke lima tabel RANCANGAN.
--
-- Nama / jalur / kolom = workbook rancangan (`loader/skema_gen.go`, aturan loader V-30) `[terverifikasi]`, dibuat UTUH:
--   T_SCORINGRISK         `ScoringRisk`, induk T_GENERAL_POLIS (PARENT_ID = ID kasus VARCHAR2(32), butir 76.1), satu per kasus;
--   T_SCORINGRESULT       `ScoringRisk/ScoringResult` - 16 bendera teks "true" / "false" (butir 68.1), satu per kasus;
--   T_DATASCORINGRISKLIST `ScoringRisk/DataScoringRiskList` - kolom Top Risk (SEQ_NO 1) / Dominant Risk (SEQ_NO 2);
--   T_SCORING_FACTOR      `…/ScoringFactor` - 24 sub-faktor (FACTOR_GROUP / FACTOR_NAME = nama halaman Pega);
--   T_SCORING_OPTION      `…/ScoringOption` - ChechBoxN / ScoreN (OPTION_NO = N).
-- Amandemen loader (tiket 54): INDEX_LOCATION (`.IndexLocation` Dominant Risk, ObjectNo VARCHAR2(50) - tidak di rancangan,
-- 0 sampel) dan PERCENT_LOSS_RATIO (`.LossRatio.LossRatio.PercentLossRatio`, 2 sampel di penampung); lebar
-- TOP_RISK_LOCATION 4000 (= T_RISKLOCATION.ASM_ADDRESS, 192), OCCUPATION_CODE / OCCUPATION_NOTE 1000 (= T_OCCUPATIONLIST
-- OCCUPATION_ID / NAME, 189) - pola butir 80. Skor / persen NUMBER(38,8) (rancangan NUMBER polos - pola 193). ID NUMBER(19)
-- dari sequence (A92); PARENT_ID ber-FK; satu T_SCORINGRISK / T_SCORINGRESULT per induk (UNIQUE).
-- Ditulis, TIDAK dijalankan agent. Nol COMMIT (ADR-U-0029).
CREATE TABLE {skema}.T_SCORINGRISK (
  ID               NUMBER(19) NOT NULL,
  IDPEGA           VARCHAR2(50),
  COB_GROUP        VARCHAR2(20),
  PARENT_ID        VARCHAR2(32) NOT NULL,
  FINAL_SCORE      NUMBER(38,8),
  NOTE_FINAL_SCORE VARCHAR2(500),
  STATUS           VARCHAR2(50),
  CONSTRAINT PK_T_SCORINGRISK PRIMARY KEY (ID),
  CONSTRAINT UQ_T_SCORINGRISK_PARENT UNIQUE (PARENT_ID),
  CONSTRAINT FK_SCORINGRISK_GENERAL FOREIGN KEY (PARENT_ID) REFERENCES {skema}.T_GENERAL_POLIS (ID)
)
/
CREATE SEQUENCE {skema}.SEQ_T_SCORINGRISK START WITH 1 INCREMENT BY 1 NOCACHE NOCYCLE
/
