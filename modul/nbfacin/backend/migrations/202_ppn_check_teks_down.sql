-- Jalur mundur 202 - PPN_CHECK kembali NUMBER(5): 'true' -> 1, 'false' -> 0, teks lain / NULL -> NULL. Pola sama dengan
-- jalur maju (tambah kolom sementara -> salin -> buang -> tambah -> salin balik -> buang), DROP berpelindung katalog.
ALTER TABLE {skema}.T_GENERAL_POLIS ADD (
  PPN_CHECK_ANGKA NUMBER(5)
)
/
UPDATE {skema}.T_GENERAL_POLIS SET PPN_CHECK_ANGKA = CASE PPN_CHECK WHEN 'true' THEN 1 WHEN 'false' THEN 0 END
 WHERE PPN_CHECK IS NOT NULL
/
DECLARE
  n NUMBER;
BEGIN
  SELECT COUNT(*) INTO n FROM SYS.ALL_TAB_COLUMNS
   WHERE OWNER = UPPER('{skema}') AND TABLE_NAME = 'T_GENERAL_POLIS' AND COLUMN_NAME = 'PPN_CHECK';
  IF n > 0 THEN
    EXECUTE IMMEDIATE 'ALTER TABLE {skema}.T_GENERAL_POLIS DROP COLUMN PPN_CHECK';
  END IF;
END;
/
