  IF n = 0 THEN
    EXECUTE IMMEDIATE 'ALTER TABLE {skema}.RIRISK_LIFE ADD CONSTRAINT ENSURE_M_RIRISK_LIFE_JSON CHECK (JSONDATA IS JSON)';
  END IF;
