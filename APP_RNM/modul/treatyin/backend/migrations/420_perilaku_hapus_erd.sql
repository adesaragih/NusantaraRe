-- FK_KONTRAK_DISALIN_DARI: KONTRAK 1--o< KONTRAK [hapus: PUTUS] — ERD.md §2.1
--
-- Kunci asing ini BELUM PERNAH ADA: kolomnya berdiri sejak migrasi 401, tetapi
-- tanpa kunci asing sama sekali. Karena itu ia DIBUAT di sini, bukan dibongkar
-- lalu dibuat ulang - nol DROP yang mendahuluinya.
--
-- Satu-satunya relasi `putus` di seluruh modul: kontrak salinan BERTAHAN ketika
-- asalnya dihapus, rujukannya saja yang dikosongkan. Kontrak salinan punya
-- versinya sendiri, dan versi itu memuat angka yang pernah dibukukan.
ALTER TABLE {skema}.KONTRAK ADD CONSTRAINT FK_KONTRAK_DISALIN_DARI
  FOREIGN KEY (ID_KONTRAK_DISALIN_DARI) REFERENCES {skema}.KONTRAK (ID_KONTRAK) ON DELETE SET NULL
/
CREATE INDEX {skema}.IX_KONTRAK_DISALIN_DARI ON {skema}.KONTRAK (ID_KONTRAK_DISALIN_DARI)
