-- ⚠️ KENAPA KOREKTIF, BUKAN SUNTINGAN DI TEMPAT
--
-- Ronde sebelumnya menyunting ke-21 kunci asing langsung di migrasi 400-419,
-- dengan alasan tertulis bahwa POOLDATA akan dibersihkan sehingga sejarah
-- T_MIGRASI di sana ikut terbuang. Pemilik proses kemudian menyatakan POOLDATA
-- adalah SKEMA SASARAN - ia tidak dibersihkan dan tidak diganti.
--
-- Dengan begitu suntingan di tempat membuat berkas migrasi MENYIMPANG dari yang
-- tercatat di T_MIGRASI: tiap pemasangan baru akan membaca berkas yang berbeda
-- dari yang pernah dijalankan. Syarat pembalikan yang ditulis sendiri di
-- KEPUTUSAN-PENYELARASAN-REPO.md §9 karena itu kepicu, dan berkas ini adalah
-- pembalikannya.
--
-- ⛔ SEPASANG DROP + ADD, bukan satu ALTER: Oracle TIDAK dapat mengubah aturan
-- hapus sebuah kunci asing yang sudah berdiri. Satu-satunya jalan membongkarnya
-- lalu membuatnya kembali.
--
-- ⛔ INDEX TIDAK IKUT DIBONGKAR. Index kunci asing dibuat terpisah di migrasi
-- aslinya dan tidak bergantung pada constraint-nya.
--
